# -*- coding: utf-8 -*-
"""File layout of the BepInEx + XUnity.AutoTranslator runtime inside a game folder.

Shared by the profiler (is the runtime really installed?), the installer and the
patch exporter (what belongs to the runtime). Kept dependency-free so profiling a
game never imports the downloader or archive libraries.
"""

from __future__ import annotations

from pathlib import Path

# Doorstop proxies that make the game load BepInEx (one of the DLLs is enough).
# Linux builds load Doorstop through ``libdoorstop.so`` started by ``run_bepinex.sh``.
LINUX_LAUNCH_SCRIPT = "run_bepinex.sh"
PROXY_DLLS: tuple[str, ...] = (
    "winhttp.dll", "version.dll", "doorstop_config.ini", "libdoorstop.so", LINUX_LAUNCH_SCRIPT,
)
PROXY_LIBRARIES: tuple[str, ...] = ("winhttp.dll", "version.dll", "libdoorstop.so")
BEPINEX_CORE_DIR = Path("BepInEx") / "core"
# XUnity.AutoTranslator ships these plugin folders (verified against the 5.5.0 and 5.6.2 packages).
XUNITY_PLUGIN_DIRS: tuple[Path, ...] = (
    Path("BepInEx") / "plugins" / "XUnity.AutoTranslator",
    Path("BepInEx") / "plugins" / "XUnity.ResourceRedirector",
)
AUTOTRANSLATOR_CONFIG = Path("BepInEx") / "config" / "AutoTranslatorConfig.ini"
# BepInEx 6 (IL2CPP) runtime pieces: its own .NET, and the Unity base libraries it
# downloads from unity.bepinex.dev on the first launch when they are missing.
IL2CPP_RUNTIME_MARKER = Path("BepInEx") / "core" / "BepInEx.Unity.IL2CPP.dll"
UNITY_BASE_LIBS_DIR = Path("BepInEx") / "unity-libs"
# Written by UnityLocalizer after a successful install: which package flavour was deployed.
RUNTIME_MARKER = Path("BepInEx") / "UnityLocalizer.runtime.json"
# BepInEx writes this on every game start; it is the proof that the hook really loaded.
BEPINEX_LOG = Path("BepInEx") / "LogOutput.log"


# XUnity loads every *.txt under Translation\{Lang}\Text. Its own OutputFile
# (_AutoGeneratedTranslations.txt) has the lowest priority, is pruned and rewritten by
# XUnity on startup and ignores regex entries, as do all files starting with "_".
# UnityLocalizer therefore owns a separate file with normal priority and regex support.
DICTIONARY_FILE = "UnityLocalizer.txt"
SUBSTITUTIONS_FILE = "_Substitutions.txt"
XUNITY_TEXT_DIRECTORY = r"Translation\{Lang}\Text"


def safe_lang_segment(target_lang: str) -> str:
    """Sanitize a language code for safe use as a single path/filename component."""
    cleaned = "".join(ch for ch in (target_lang or "").strip() if ch.isalnum() or ch in ("-", "_"))
    return cleaned or "en"


def dictionary_path(game_dir: Path | str, target_lang: str) -> Path:
    """XUnity static dictionary the pipeline writes for a language."""
    return Path(game_dir) / "BepInEx" / "Translation" / safe_lang_segment(target_lang) / "Text" / DICTIONARY_FILE


def substitutions_path(game_dir: Path | str, target_lang: str) -> Path:
    """XUnity runtime substitutions file for glossary and fixed terminology."""
    return Path(game_dir) / "BepInEx" / "Translation" / safe_lang_segment(target_lang) / "Text" / SUBSTITUTIONS_FILE


def proxy_present(game_dir: Path | str) -> bool:
    """True when any Doorstop proxy file is in the game root (something to uninstall)."""
    root = Path(game_dir)
    return any((root / name).is_file() for name in PROXY_DLLS)


def runtime_hook_ready(game_dir: Path | str) -> bool:
    """True only when the game will actually load XUnity: proxy DLL, BepInEx core and plugin.

    The pipeline creates ``BepInEx/Translation`` and ``BepInEx/config`` even when no
    hook is installed, so the mere existence of a ``BepInEx`` folder proves nothing.
    """
    root = Path(game_dir)
    has_proxy = any((root / name).is_file() for name in PROXY_LIBRARIES)
    return has_proxy and (root / BEPINEX_CORE_DIR).is_dir() and (root / XUNITY_PLUGIN_DIRS[0]).is_dir()


def runtime_flavor_matches(game_dir: Path | str, is_il2cpp: bool) -> bool:
    """True when the installed BepInEx is the right generation: 6 for IL2CPP, 5 for Mono.

    Only BepInEx 6 IL2CPP ships ``BepInEx.Unity.IL2CPP.dll``; a Mono game with it, or an
    IL2CPP game without it, has a hook that can never work.
    """
    has_il2cpp_core = (Path(game_dir) / IL2CPP_RUNTIME_MARKER).is_file()
    return has_il2cpp_core == is_il2cpp
