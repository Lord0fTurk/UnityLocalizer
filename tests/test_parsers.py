def test_yarn_apply_never_touches_control_lines(tmp_path: Path) -> None:
    yarn_file = tmp_path / "dialogue.yarn"
    yarn_file.write_text("title: Start\n---\n<<jump End>>\n// Hello\nHello\n===\n", encoding="utf-8")

    parser = StreamingAssetsParser()
    assert parser.extract_strings(yarn_file) == ["Hello"]
    translations = {"<<jump End>>": "<<atla Son>>", "// Hello": "// Merhaba", "Hello": "Merhaba"}
    assert parser.apply_translations(yarn_file, translations) is True

    lines = yarn_file.read_text(encoding="utf-8-sig").splitlines()
    assert lines == ["title: Start", "---", "<<jump End>>", "// Hello", "Merhaba", "==="]


def test_streaming_rerun_reads_original_text_from_backup(tmp_path: Path) -> None:
    """A second pipeline run must harvest and patch the source text, not the last translation."""
    path = tmp_path / "dialog.json"
    path.write_text(json.dumps({"text": "Open the door"}), encoding="utf-8")
    parser = StreamingAssetsParser()

    assert parser.apply_translations(path, {"Open the door": "Kapıyı aç"})
    assert parser.extract_strings(path) == ["Open the door"]  # not "Kapıyı aç"

    assert parser.apply_translations(path, {"Open the door": "Kapıyı açın"})
    assert json.loads(path.read_text(encoding="utf-8")) == {"text": "Kapıyı açın"}
    assert json.loads((tmp_path / "dialog.json.bak").read_text(encoding="utf-8")) == {"text": "Open the door"}


def test_yarn_backup_keeps_yarn_handling(tmp_path: Path) -> None:
    path = tmp_path / "intro.yarn"
    path.write_text("title: Start\n---\nGuard: Halt!\n===\n", encoding="utf-8")
    parser = StreamingAssetsParser()
    parser.apply_translations(path, {"Halt!": "Dur!"})
    parser.apply_translations(path, {"Halt!": "Durun!"})
    assert "Guard: Durun!" in path.read_text(encoding="utf-8-sig")


def test_naninovel_streaming_file_keeps_inline_commands_and_line_endings(tmp_path: Path) -> None:
    nani = tmp_path / "Intro.nani"
    nani.write_bytes(
        b"; comment\r\n# Start\r\n@back School\r\n"
        b"Kohaku.Happy: Hello there![i] Ready to go?[wait 1]\r\n"
        b'@choice "Yes, let\'s go" goto:.Go\r\n'
    )
    parser = StreamingAssetsParser()
    assert parser.extract_strings(nani) == ["Hello there!", "Ready to go?", "Yes, let's go"]

    parser.apply_translations(nani, {
        "Hello there!": "Merhaba!", "Ready to go?": "Hazır mısın?", "Yes, let's go": "Evet, gidelim",
    })
    assert nani.read_bytes().decode("utf-8-sig") == (
        "; comment\r\n# Start\r\n@back School\r\n"
        "Kohaku.Happy: Merhaba![i] Hazır mısın?[wait 1]\r\n"
        '@choice "Evet, gidelim" goto:.Go\r\n'
    )
    assert parser.extract_strings(nani)[0] == "Hello there!"  # re-runs read the original
