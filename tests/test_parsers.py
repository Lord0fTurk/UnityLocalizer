def test_streaming_assets_json(tmp_path: Path):
    sample_json = {
        "id": "quest_01",
        "title": "Save the Princess",
        "description": "Travel to the dark castle.",
        "rewards": ["100 Gold", "Iron Sword"]
    }
    json_file = tmp_path / "quest.json"
    json_file.write_text(json.dumps(sample_json), encoding="utf-8")

    parser = StreamingAssetsParser()
    strings = parser.extract_strings(json_file)

    assert "quest_01" not in strings  # Ignored key 'id'
    assert "Save the Princess" in strings
    assert "Travel to the dark castle." in strings
    assert "100 Gold" in strings

    translations = {
        "Save the Princess": "Prensesi Kurtar",
        "Travel to the dark castle.": "Karanlık kaleye seyahat et.",
        "100 Gold": "100 Altın",
        "Iron Sword": "Demir Kılıç"
    }
    success = parser.apply_translations(json_file, translations)
    assert success is True

    updated_data = json.loads(json_file.read_text(encoding="utf-8"))
    assert updated_data["title"] == "Prensesi Kurtar"
    assert updated_data["id"] == "quest_01"  # Retained original id


def test_auto_translator_dictionary(tmp_path: Path):
    dict_content = "New Game=New Game\nContinue=Continue\nOptions=Options\n"
    dict_file = tmp_path / "_AutoGeneratedTranslations.txt"
    dict_file.write_text(dict_content, encoding="utf-8")

    parser = AutoTranslatorParser()
    keys = parser.extract_strings(dict_file)

    assert keys == ["New Game", "Continue", "Options"]

    translations = {
        "New Game": "Yeni Oyun",
        "Continue": "Devam Et",
        "Options": "Seçenekler"
    }
    parser.apply_translations(dict_file, translations)

    content = dict_file.read_text(encoding="utf-8")
    assert "New Game=Yeni Oyun" in content
    assert "Continue=Devam Et" in content
    assert "Options=Seçenekler" in content


def test_i2_csv_export_translates_source_column_and_keeps_keys(tmp_path: Path):
    """I2 spreadsheet exports go through the column-aware string table rules."""
    csv_content = "Key,Type,Desc,English [en],Turkish [tr]\nUI_PLAY,Text,,Play Game,\nUI_QUIT,Text,,Quit,\n"
    csv_file = tmp_path / "I2Languages.csv"
    csv_file.write_text(csv_content, encoding="utf-8")

    parser = StreamingAssetsParser(source_lang="en", target_lang="tr")
    assert parser.extract_strings(csv_file) == ["Play Game", "Quit"]

    parser.apply_translations(csv_file, {"Play Game": "Oyunu Oyna", "Quit": "Çıkış"})
    rows = csv_file.read_text(encoding="utf-8-sig").splitlines()
    assert rows[1] == "UI_PLAY,Text,,Oyunu Oyna,Oyunu Oyna"  # key untouched, empty target cell filled
    assert rows[2].startswith("UI_QUIT,")


