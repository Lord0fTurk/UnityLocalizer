# -*- coding: utf-8 -*-
"""Tests for XUnity dictionary codec, strict syntax validation and the gated runner."""

from pathlib import Path

from src.core.parsers import xunity_codec
from src.core.parsers.auto_translator import AutoTranslatorParser
from src.core.pipeline.translation_runner import BatchTranslationRunner
from src.core.syntax_guard import UnitySyntaxGuard
from src.core.translators.base import TranslationEngine, TranslationResult


def test_codec_round_trip_special_chars() -> None:
    key = "HP=100\nPress \\ to <b>jump</b>"
    value = "CAN=100\n<b>Zıpla</b> için \\ bas"
    line = xunity_codec.encode_line(key, value)
    assert "\n" not in line
    assert xunity_codec.decode_line(line) == (key, value)


def test_parser_preserves_untouched_lines_and_escapes_new(tmp_path: Path) -> None:
    dict_file = tmp_path / "_AutoGeneratedTranslations.txt"
    dict_file.write_text("// header\nA\\=B=Old\nKeep=Me\n", encoding="utf-8")
    parser = AutoTranslatorParser()

    assert parser.extract_strings(dict_file) == ["A=B", "Keep"]
    parser.apply_translations(dict_file, {"A=B": "Yeni", "Two\nLines": "İki\nSatır"})

    lines = dict_file.read_text(encoding="utf-8-sig").splitlines()
    assert lines == ["// header", "A\\=B=Yeni", "Keep=Me", "Two\\nLines=İki\\nSatır"]


def test_validator_rejects_dropped_and_mangled_tokens() -> None:
    orig = "<color=#FF0000>{0}</color> damage, %s left"
    assert UnitySyntaxGuard.validate_integrity(orig, "<color=#FF0000>{0}</color> hasar, %s kaldı")[0]
    assert not UnitySyntaxGuard.validate_integrity(orig, "<color=#FF0000>0</color> hasar, %s kaldı")[0]
    assert not UnitySyntaxGuard.validate_integrity(orig, "{0} hasar, %s kaldı</color>")[0]
    assert not UnitySyntaxGuard.validate_integrity("Hi {0}", "Selam ⟦ULPH_0⟧")[0]


class _FakeManager:
    """Returns canned translations keyed by source text."""

    def __init__(self, canned: dict[str, str]) -> None:
        self.canned = canned
        self.source_langs: list[str] = []

    def translate_batch(
        self,
        texts: list[str],
        source_lang: str = "auto",
        target_lang: str = "tr",
        engine_type: TranslationEngine = TranslationEngine.GOOGLE,
    ) -> list[TranslationResult]:
        self.source_langs.append(source_lang)
        return [
            TranslationResult(
                original_text=t,
                translated_text=self.canned.get(t, ""),
                source_lang="en",
                target_lang=target_lang,
                engine=engine_type,
                success=t in self.canned,
            )
            for t in texts
        ]


def test_runner_filters_broken_and_identity_results() -> None:
    canned = {"Gold: {0}": "Altın: 0", "Start": "Başla", "OK": "OK"}
    runner = BatchTranslationRunner(_FakeManager(canned), batch_size=2)  # type: ignore[arg-type]
    report = runner.run(["Gold: {0}", "Start", "OK", "Missing"], "tr", TranslationEngine.GOOGLE)

    assert report.translations == {"Start": "Başla"}
    assert "Gold: {0}" in report.rejected
    assert report.unchanged == 1
    assert report.failed == 1


def test_runner_forwards_source_language() -> None:
    manager = _FakeManager({"Start": "Başla"})
    runner = BatchTranslationRunner(manager, batch_size=1)  # type: ignore[arg-type]
    runner.run(["Start", "Quit"], "tr", TranslationEngine.GOOGLE, source_lang="ja")
    assert manager.source_langs == ["ja", "ja"]


def test_resolve_source_language() -> None:
    from src.core.parsers.loc_table import resolve_source_language

    assert resolve_source_language("auto") == "en"
    assert resolve_source_language("") == "en"
    assert resolve_source_language("ja") == "ja"
    assert resolve_source_language("zh-CN") == "zh-CN"


def test_autotranslator_config_uses_source_language(tmp_path) -> None:  # type: ignore[no-untyped-def]
    from src.core.hook_manager.font_bootstrap import FontBootstrap

    assert FontBootstrap.inject_font(tmp_path, target_lang="tr", source_lang="ja") is True
    ini = (tmp_path / "BepInEx" / "config" / "AutoTranslatorConfig.ini").read_text(encoding="utf-8-sig")
    assert "FromLanguage=ja" in ini
    assert "Language=tr" in ini
